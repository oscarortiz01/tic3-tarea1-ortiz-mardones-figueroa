static int s_wifi_retry_count = 0;
static int s_active_ap_index = 0; // 0 = HOTSPOT (TIC3_RED, Preferencial), 1 = LAB (Fallback)

static void wifi_apply_current_ap(void) {
    wifi_config_t sta_cfg;
    memset(&sta_cfg, 0, sizeof(sta_cfg));

    if (s_active_ap_index == 0) {
        strncpy((char*)sta_cfg.sta.ssid, WIFI_SSID_HOTSPOT, sizeof(sta_cfg.sta.ssid));
        strncpy((char*)sta_cfg.sta.password, WIFI_PASS_HOTSPOT, sizeof(sta_cfg.sta.password));
        strncpy(s_target_server_ip, SERVER_IP_HOTSPOT, sizeof(s_target_server_ip));
        ESP_LOGI(TAG_NET, "Conectando PREFERENCIALMENTE a Hotspot TIC3_RED: '%s' (Servidor: %s:%d)",
                 WIFI_SSID_HOTSPOT, s_target_server_ip, s_target_server_port);
    } else {
        strncpy((char*)sta_cfg.sta.ssid, WIFI_SSID_LAB, sizeof(sta_cfg.sta.ssid));
        strncpy((char*)sta_cfg.sta.password, WIFI_PASS_LAB, sizeof(sta_cfg.sta.password));
        strncpy(s_target_server_ip, SERVER_IP_LAB, sizeof(s_target_server_ip));
        ESP_LOGI(TAG_NET, "Conectando a red del Laboratorio (Fallback): '%s' (Servidor: %s:%d)",
                 WIFI_SSID_LAB, s_target_server_ip, s_target_server_port);
    }

    sta_cfg.sta.threshold.authmode = WIFI_AUTH_WPA2_PSK;
    sta_cfg.sta.pmf_cfg.capable = true;
    sta_cfg.sta.pmf_cfg.required = false;

    esp_wifi_set_config(WIFI_IF_STA, &sta_cfg);
}

static void wifi_event_handler(void* arg, esp_event_base_t event_base,
                               int32_t event_id, void* event_data)
{
    if (event_base == WIFI_EVENT && event_id == WIFI_EVENT_STA_START) {
        wifi_apply_current_ap();
        esp_wifi_connect();
    } else if (event_base == WIFI_EVENT && event_id == WIFI_EVENT_STA_DISCONNECTED) {
        wifi_event_sta_disconnected_t *disconn = (wifi_event_sta_disconnected_t*) event_data;
        ESP_LOGW(TAG_NET, "Desconectado de WiFi (motivo: %d).", disconn ? disconn->reason : -1);
        xEventGroupClearBits(s_wifi_event_group, WIFI_CONNECTED_BIT);

        s_wifi_retry_count++;
        if (s_wifi_retry_count >= 3) {
            s_wifi_retry_count = 0;
            s_active_ap_index = (s_active_ap_index == 0) ? 1 : 0;
            ESP_LOGW(TAG_NET, "Cambiando a AP alternativo...");
            wifi_apply_current_ap();
        }
        esp_wifi_connect();
    } else if (event_base == IP_EVENT && event_id == IP_EVENT_STA_GOT_IP) {
        ip_event_got_ip_t* event = (ip_event_got_ip_t*) event_data;
        ESP_LOGI(TAG_NET, "WiFi Conectado! IP asignada: " IPSTR, IP2STR(&event->ip_info.ip));
        s_wifi_retry_count = 0;
        xEventGroupSetBits(s_wifi_event_group, WIFI_CONNECTED_BIT);
    }
}

static void wifi_init_sta(void) {
    s_wifi_event_group = xEventGroupCreate();

    ESP_ERROR_CHECK(esp_netif_init());
    ESP_ERROR_CHECK(esp_event_loop_create_default());
    esp_netif_create_default_wifi_sta();

    wifi_init_config_t cfg = WIFI_INIT_CONFIG_DEFAULT();
    ESP_ERROR_CHECK(esp_wifi_init(&cfg));

    esp_event_handler_instance_t instance_any_id;
    esp_event_handler_instance_t instance_got_ip;
    ESP_ERROR_CHECK(esp_event_handler_instance_register(WIFI_EVENT, ESP_EVENT_ANY_ID,
                                                        &wifi_event_handler, NULL, &instance_any_id));
    ESP_ERROR_CHECK(esp_event_handler_instance_register(IP_EVENT, IP_EVENT_STA_GOT_IP,
                                                        &wifi_event_handler, NULL, &instance_got_ip));

    ESP_ERROR_CHECK(esp_wifi_set_mode(WIFI_MODE_STA));
    ESP_ERROR_CHECK(esp_wifi_start());
    esp_wifi_set_ps(WIFI_PS_NONE);
}

static bool json_get_string(const char *json, const char *key, char *out, size_t max_len) {
    char pattern[64];
    snprintf(pattern, sizeof(pattern), "\"%s\"", key);
    const char *p = strstr(json, pattern);
    if (!p) return false;
    p += strlen(pattern);
    while (*p && (*p == ' ' || *p == ':' || *p == '\t')) p++;
    if (*p == '\"') p++;
    size_t i = 0;
    while (*p && *p != '\"' && *p != ',' && *p != '}' && *p != '\n' && *p != '\r' && i < max_len - 1) {
        out[i++] = *p++;
    }
    out[i] = '\0';
    return true;
}

static bool json_get_int(const char *json, const char *key, int *val) {
    char pattern[64];
    snprintf(pattern, sizeof(pattern), "\"%s\"", key);
    const char *p = strstr(json, pattern);
    if (!p) return false;
    p += strlen(pattern);
    while (*p && (*p == ' ' || *p == ':' || *p == '\t')) p++;
    *val = atoi(p);
    return true;
}

static void client_manager_task(void *pvParameters) {
    char rx_buf[512];

    // Asegurar que la cola FreeRTOS esté creada una sola vez
    if (s_sample_queue == NULL) {
        s_sample_queue = xQueueCreate(QUEUE_CAPACITY, sizeof(sample_data_t));
        assert(s_sample_queue != NULL);
    }

    while (1) {
        ESP_LOGI(TAG_NET, "Esperando red WiFi antes de iniciar conexion...");
        xEventGroupWaitBits(s_wifi_event_group, WIFI_CONNECTED_BIT, pdFALSE, pdTRUE, portMAX_DELAY);

        struct sockaddr_in dest_addr;
        memset(&dest_addr, 0, sizeof(dest_addr));
        inet_pton(AF_INET, s_target_server_ip, &dest_addr.sin_addr);
        dest_addr.sin_family = AF_INET;
        dest_addr.sin_port = htons(s_target_server_port);

        int sock = socket(AF_INET, SOCK_STREAM, IPPROTO_IP);
        if (sock < 0) {
            ESP_LOGE(TAG_NET, "No se pudo crear socket TCP: errno %d", errno);
            vTaskDelay(pdMS_TO_TICKS(2000));
            continue;
        }

        struct timeval tv = { .tv_sec = 2, .tv_usec = 0 };
        setsockopt(sock, SOL_SOCKET, SO_RCVTIMEO, &tv, sizeof(tv));
        setsockopt(sock, SOL_SOCKET, SO_SNDTIMEO, &tv, sizeof(tv));
        int nodelay = 1;
        setsockopt(sock, IPPROTO_TCP, TCP_NODELAY, &nodelay, sizeof(nodelay));

        ESP_LOGI(TAG_NET, "Conectando al servidor Raspberry Pi en %s:%d...", s_target_server_ip, s_target_server_port);
        if (connect(sock, (struct sockaddr *)&dest_addr, sizeof(dest_addr)) != 0) {
            ESP_LOGW(TAG_NET, "No se pudo conectar a %s:%d (errno %d). Reintentando en 2s...",
                     s_target_server_ip, s_target_server_port, errno);
            close(sock);
            vTaskDelay(pdMS_TO_TICKS(2000));
            continue;
        }

        ESP_LOGI(TAG_NET, "CONECTADO AL SERVIDOR TIC3 EN %s:%d", s_target_server_ip, s_target_server_port);
        s_active_tcp_sock = sock;

        // Enviar aviso de disponibilidad al servidor
        const char *handshake = "{\"status\":\"ready\",\"device\":\"esp32_bmi270\"}\n";
        send_all(sock, handshake, strlen(handshake));

        char line_buffer[512];
        int line_pos = 0;
        bool reconnect_requested = false;

        while (1) {
            if (!(xEventGroupGetBits(s_wifi_event_group) & WIFI_CONNECTED_BIT)) {
                ESP_LOGW(TAG_NET, "WiFi desconectado.");
                break;
            }

            int r = recv(sock, rx_buf, sizeof(rx_buf) - 1, 0);
            if (r > 0) {
                rx_buf[r] = '\0';
                for (int i = 0; i < r; i++) {
                    char c = rx_buf[i];
                    if (c == '\n' || c == '\r') {
                        if (line_pos > 0) {
                            line_buffer[line_pos] = '\0';
                            ESP_LOGI(TAG_NET, "Configuracion JSON recibida: %s", line_buffer);

                            char cmd[32] = "";
                            json_get_string(line_buffer, "cmd", cmd, sizeof(cmd));

                            if (strcmp(cmd, "start") == 0) {
                                stop_current_session();

                                int odr = 100, range = 8, samples = 1000, port = 0;
                                char proto[16] = "TCP";
                                char mode[32] = "parallel";

                                json_get_int(line_buffer, "odr", &odr);
                                json_get_int(line_buffer, "range", &range);
                                json_get_int(line_buffer, "samples", &samples);
                                json_get_int(line_buffer, "port", &port);
                                json_get_string(line_buffer, "protocol", proto, sizeof(proto));
                                json_get_string(line_buffer, "mode", mode, sizeof(mode));

                                s_cfg_odr = odr;
                                s_cfg_range = range;
                                s_cfg_samples = samples;
                                if (port > 0) s_target_server_port = port;
                                strncpy(s_cfg_protocol, proto, sizeof(s_cfg_protocol) - 1);
                                strncpy(s_cfg_mode, mode, sizeof(s_cfg_mode) - 1);

                                // Reconfiguración del sensor en tiempo de ejecución
                                reconfigure_sensor(s_cfg_odr, s_cfg_range);

                                // Configuración socket UDP si corresponde
                                if (strcmp(s_cfg_protocol, "UDP") == 0) {
                                    s_active_udp_sock = socket(AF_INET, SOCK_DGRAM, IPPROTO_IP);
                                    memset(&s_udp_dest_addr, 0, sizeof(s_udp_dest_addr));
                                    inet_pton(AF_INET, s_target_server_ip, &s_udp_dest_addr.sin_addr);
                                    s_udp_dest_addr.sin_family = AF_INET;
                                    s_udp_dest_addr.sin_port = htons(s_target_server_port);
                                }

                                xQueueReset(s_sample_queue);
                                s_session_running = true;
                                s_acq_done = false;
                                s_tx_done = false;

                                if (strcmp(s_cfg_mode, "parallel") == 0) {
                                    xTaskCreatePinnedToCore(task_sensor_acq_parallel, "acq_c0", 4096, NULL,
                                                            6, &s_acq_task_handle, 0);
                                    xTaskCreatePinnedToCore(task_network_tx_parallel, "tx_c1", 8192, NULL,
                                                            5, &s_tx_task_handle, 1);
                                } else {
                                    xTaskCreatePinnedToCore(task_acq_tx_sequential, "seq_c1", 8192, NULL,
                                                            5, &s_seq_task_handle, 1);
                                }

                                const char *ack = "{\"status\":\"started\"}\n";
                                send_all(sock, ack, strlen(ack));

                            } else if (strcmp(cmd, "stop") == 0) {
                                ESP_LOGI(TAG_NET, "Comando STOP recibido");
                                stop_current_session();
                                const char *ack = "{\"status\":\"stopped\"}\n";
                                send_all(sock, ack, strlen(ack));
                            } else if (strcmp(cmd, "set_port") == 0) {
                                // La GUI cambió el puerto del servidor: reconectar al nuevo puerto
                                int new_port = 0;
                                json_get_int(line_buffer, "port", &new_port);
                                if (new_port >= 1024 && new_port <= 65535) {
                                    stop_current_session();
                                    s_target_server_port = new_port;
                                    ESP_LOGI(TAG_NET, "Nuevo puerto de servidor: %d. Reconectando...", new_port);
                                    reconnect_requested = true;
                                }
                            }

                            line_pos = 0;
                        }
                    } else if (line_pos < sizeof(line_buffer) - 1) {
                        line_buffer[line_pos++] = c;
                    }
                }
                if (reconnect_requested) break;
            } else if (r == 0) {
                ESP_LOGW(TAG_NET, "El servidor cerro la conexion TCP.");
                break;
            } else {
                if (errno != EAGAIN && errno != EWOULDBLOCK) {
                    ESP_LOGE(TAG_NET, "Error en conexion TCP: errno %d", errno);
                    break;
                }
            }

            // Notificar fin de sesión al cliente cuando termina la transmisión
            if (s_session_running && s_tx_done) {
                stop_current_session();
                const char *done_msg = "{\"status\":\"idle\",\"message\":\"session_completed\"}\n";
                send_all(sock, done_msg, strlen(done_msg));
                ESP_LOGI(TAG_NET, "Sesión de adquisición completada.");
            }

            vTaskDelay(pdMS_TO_TICKS(10));
        }

        stop_current_session();
        close(sock);
        s_active_tcp_sock = -1;
        ESP_LOGW(TAG_NET, "Reconectando en 2 segundos...");
        vTaskDelay(pdMS_TO_TICKS(2000));
    }
}

