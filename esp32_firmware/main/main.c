static i2c_master_bus_handle_t bus_handle = NULL;

void app_main(void) {
    ESP_LOGI(TAG, "=== BMI270 + FreeRTOS WiFi Adquisicion TIC3 ===");

    // Reconfiguración del Task Watchdog Timer: no verificar tareas idle para evitar panics en alta frecuencia
    esp_task_wdt_config_t twdt_cfg = {
        .timeout_ms = 10000,
        .idle_core_mask = 0,
        .trigger_panic = false,
    };
    esp_task_wdt_reconfigure(&twdt_cfg);

    // 0. Memoria NVS
    esp_err_t nvs_err = nvs_flash_init();
    if (nvs_err == ESP_ERR_NVS_NO_FREE_PAGES || nvs_err == ESP_ERR_NVS_NEW_VERSION_FOUND) {
        ESP_ERROR_CHECK(nvs_flash_erase());
        nvs_err = nvs_flash_init();
    }
    ESP_ERROR_CHECK(nvs_err);

    // 1. Bus I2C maestro
    ESP_ERROR_CHECK(i2c_master_init(&bus_handle));
    ESP_LOGI(TAG, "Bus I2C listo (SDA=%d SCL=%d, %lu Hz)",
             I2C_MASTER_SDA_IO, I2C_MASTER_SCL_IO, (unsigned long)I2C_MASTER_FREQ_HZ);

    // 2. Sensor BMI270 (Carga de microcódigo firmware e inicialización inicial)
    ret = bmi270_init(bus_handle, ACC_ODR, ACC_AVG, ACC_RANGE, GYR_ODR, GYR_RANGE);
    if (ret != ESP_OK) {
        ESP_LOGE(TAG, "Fallo al inicializar BMI270: %s", esp_err_to_name(ret));
    } else {
        ESP_LOGI(TAG, "BMI270 inicializado. Listo para recibir configuracion JSON desde RPi.");
    }

    // 3. Red Wi-Fi STA
    wifi_init_sta();

    // 4. Lanzar tarea cliente TCP de control y adquisición
    xTaskCreate(client_manager_task, "client_mgr", 8192, NULL, 5, NULL);
}