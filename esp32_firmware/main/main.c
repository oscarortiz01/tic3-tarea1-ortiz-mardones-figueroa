/* Habilita y deshabilita sensores auxiliar, giroscopio, acelerómetro y temperatura. 
 * Cada parámetro recibe solo 1's o 0's. */
static void toggle_sensors(int aux, int gyr, int acc, int temp) {
    uint8_t reg_pwr_ctrl = 0x7D;
    uint8_t val_pwr_ctrl;

    if ((aux != 0 && aux != 1) || (gyr != 0 && gyr != 1) || (acc != 0 && acc != 1) || (temp != 0 && temp != 1)) {
        ESP_LOGE(TAG, "PARÁMETRO INCORRECTO EN FUNCIÓN toggle_sensors.");
    }

    val_pwr_ctrl = (temp << 3) | (acc << 2) | (gyr << 1) | aux;

    ret = device_write(s_dev, &reg_pwr_ctrl, &val_pwr_ctrl, 1, TAG);
    if (ret != ESP_OK) {
        ESP_LOGE(TAG, "Error escribiendo pwr_ctrl: %s", esp_err_to_name(ret));
    }
}

