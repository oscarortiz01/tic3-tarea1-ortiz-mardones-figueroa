static volatile bool s_session_running = false;
static volatile bool s_acq_done = false;
static volatile bool s_tx_done = false;

static int s_cfg_odr = 100;
static int s_cfg_range = 8;
static int s_cfg_samples = 1000;
static char s_cfg_protocol[8] = "TCP";
static char s_cfg_mode[16] = "parallel";

static TaskHandle_t s_acq_task_handle = NULL;
static TaskHandle_t s_tx_task_handle = NULL;
static TaskHandle_t s_seq_task_handle = NULL;

static int s_active_tcp_sock = -1;
static int s_active_udp_sock = -1;
static struct sockaddr_in s_udp_dest_addr;

// Tarea Núcleo 0: Adquisición periódica estricta sin bloqueos de red
static void task_sensor_acq_parallel(void *arg) {
    ESP_LOGI(TAG, "[Core 0] Adquisicion periodica iniciada: %d Hz (Meta: %d muestras)",
             s_cfg_odr, s_cfg_samples);
    int64_t period_us = (int64_t)(1000000.0 / (double)s_cfg_odr);
    int64_t next_sample_us = esp_timer_get_time();
    uint32_t count = 0;

    while (s_session_running && count < s_cfg_samples) {
        int64_t now = esp_timer_get_time();
        int64_t diff = next_sample_us - now;
        if (diff > 10000) {
            vTaskDelay(pdMS_TO_TICKS(diff / 1000));
        } else if (diff > 0) {
            esp_rom_delay_us((uint32_t)diff);
        }
        next_sample_us += period_us;

        sample_data_t sample;
        sample.sample_id = count;
        if (bmi270_read_sample(&sample) == ESP_OK) {
            if (s_sample_queue != NULL) {
                xQueueSend(s_sample_queue, &sample, 0);
            }
            count++;
        }
    }

    ESP_LOGI(TAG, "[Core 0] Adquisicion completada. Total: %lu muestras", (unsigned long)count);
    s_acq_done = true;
    s_acq_task_handle = NULL;
    vTaskDelete(NULL);
}

// Tarea Núcleo 1: Extracción de cola y transmisión de bloques de 1 segundo
static void task_network_tx_parallel(void *arg) {
    ESP_LOGI(TAG_NET, "[Core 1] Transmision paralela iniciada (Protocolo: %s)", s_cfg_protocol);
    uint32_t block_id = 1;
    uint32_t total_sent = 0;
    int samples_per_sec = s_cfg_odr;
    if (samples_per_sec > MAX_SAMPLES_PER_BLOCK) samples_per_sec = MAX_SAMPLES_PER_BLOCK;

    while (s_session_running && total_sent < s_cfg_samples) {
        int block_count = 0;
        int target_in_block = samples_per_sec;
        if (total_sent + target_in_block > s_cfg_samples) {
            target_in_block = s_cfg_samples - total_sent;
        }

        int64_t block_start_us = esp_timer_get_time();
        while (block_count < target_in_block && s_session_running) {
            sample_data_t item;
            if (xQueueReceive(s_sample_queue, &item, pdMS_TO_TICKS(50)) == pdTRUE) {
                s_block_samples[block_count++] = item;
            } else if (s_acq_done) {
                if (uxQueueMessagesWaiting(s_sample_queue) == 0) break;
            }
            if (esp_timer_get_time() - block_start_us > 1500000 && block_count > 0) {
                break;
            }
        }

        if (block_count > 0) {
            esp_err_t err;
            if (strcmp(s_cfg_protocol, "UDP") == 0) {
                err = transmit_udp_block(s_active_udp_sock, &s_udp_dest_addr, block_id++,
                                         s_block_samples, block_count, s_cfg_odr, s_cfg_range, "parallel");
            } else {
                err = transmit_tcp_block(s_active_tcp_sock, block_id++,
                                         s_block_samples, block_count, s_cfg_odr, s_cfg_range, "parallel");
            }
            if (err != ESP_OK) {
                ESP_LOGE(TAG_NET, "Fallo transmitiendo bloque %lu", (unsigned long)(block_id - 1));
                s_session_running = false;
                break;
            }
            total_sent += block_count;
            ESP_LOGI(TAG_NET, "[Core 1] Bloque #%lu transmitido (%d muestras, progreso: %lu/%d)",
                     (unsigned long)(block_id - 1), block_count, (unsigned long)total_sent, s_cfg_samples);
        }
    }

    ESP_LOGI(TAG_NET, "[Core 1] Transmision finalizada: %lu muestras enviadas", (unsigned long)total_sent);
    s_tx_done = true;
    s_tx_task_handle = NULL;
    vTaskDelete(NULL);
}

// Tarea Modo Secuencial: Adquisición y transmisión alternada y bloqueante
static void task_acq_tx_sequential(void *arg) {
    ESP_LOGI(TAG, "Iniciando modo SECUENCIAL (Lectura y transmision bloqueante)");
    uint32_t block_id = 1;
    uint32_t total_sent = 0;
    int samples_per_sec = s_cfg_odr;
    if (samples_per_sec > MAX_SAMPLES_PER_BLOCK) samples_per_sec = MAX_SAMPLES_PER_BLOCK;

    int64_t period_us = (int64_t)(1000000.0 / (double)s_cfg_odr);

    while (s_session_running && total_sent < s_cfg_samples) {
        int target = samples_per_sec;
        if (total_sent + target > s_cfg_samples) {
            target = s_cfg_samples - total_sent;
        }

        int block_count = 0;
        int64_t next_sample_us = esp_timer_get_time();

        // 1. Fase de Adquisición
        while (block_count < target && s_session_running) {
            int64_t now = esp_timer_get_time();
            int64_t diff = next_sample_us - now;
            if (diff > 10000) {
                vTaskDelay(pdMS_TO_TICKS(diff / 1000));
            } else if (diff > 0) {
                esp_rom_delay_us((uint32_t)diff);
            }
            next_sample_us += period_us;

            sample_data_t sample;
            sample.sample_id = total_sent + block_count;
            if (bmi270_read_sample(&sample) == ESP_OK) {
                s_block_samples[block_count++] = sample;
            }
        }

        // 2. Fase de Transmisión bloqueante
        if (block_count > 0 && s_session_running) {
            esp_err_t err;
            if (strcmp(s_cfg_protocol, "UDP") == 0) {
                err = transmit_udp_block(s_active_udp_sock, &s_udp_dest_addr, block_id++,
                                         s_block_samples, block_count, s_cfg_odr, s_cfg_range, "sequential");
            } else {
                err = transmit_tcp_block(s_active_tcp_sock, block_id++,
                                         s_block_samples, block_count, s_cfg_odr, s_cfg_range, "sequential");
            }
            if (err != ESP_OK) {
                ESP_LOGE(TAG_NET, "Fallo transmitiendo bloque secuencial");
                s_session_running = false;
                break;
            }
            total_sent += block_count;
            ESP_LOGI(TAG, "Secuencial: Bloque #%lu enviado (%d muestras, progreso: %lu/%d)",
                     (unsigned long)(block_id - 1), block_count, (unsigned long)total_sent, s_cfg_samples);
        }
    }

    s_tx_done = true;
    s_acq_done = true;
    s_seq_task_handle = NULL;
    vTaskDelete(NULL);
}

static void stop_current_session(void) {
    if (!s_session_running) return;
    s_session_running = false;

    int wait_cycles = 0;
    while ((s_acq_task_handle != NULL || s_tx_task_handle != NULL || s_seq_task_handle != NULL) && wait_cycles < 20) {
        vTaskDelay(pdMS_TO_TICKS(50));
        wait_cycles++;
    }

    if (s_active_udp_sock >= 0) {
        close(s_active_udp_sock);
        s_active_udp_sock = -1;
    }
}

