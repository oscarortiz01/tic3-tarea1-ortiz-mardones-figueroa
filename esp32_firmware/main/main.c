#define MAX_SAMPLES_PER_BLOCK 2048
#define QUEUE_CAPACITY        2048

static sample_data_t s_block_samples[MAX_SAMPLES_PER_BLOCK];
static QueueHandle_t s_sample_queue = NULL;

static esp_err_t send_all(int sock, const void *data, size_t len) {
    const char *p = (const char *)data;
    while (len > 0) {
        int sent = send(sock, p, len, 0);
        if (sent <= 0) return ESP_FAIL;
        p += sent;
        len -= sent;
    }
    return ESP_OK;
}

static esp_err_t transmit_tcp_block(int sock, uint32_t block_id, sample_data_t *samples, int count,
                                    int odr, int range, const char *mode) {
    char chunk[2048];
    int pos = snprintf(chunk, sizeof(chunk),
        "{\"type\":\"block\",\"block\":%lu,\"count\":%d,\"odr\":%d,\"range\":%d,\"mode\":\"%s\",\"protocol\":\"TCP\",\"samples\":[",
        (unsigned long)block_id, count, odr, range, mode);

    for (int i = 0; i < count; i++) {
        char sbuf[110];
        int slen = snprintf(sbuf, sizeof(sbuf), "%s[%lu,%lu,%.3f,%.3f,%.3f,%.3f,%.3f,%.3f]",
            (i > 0 ? "," : ""),
            (unsigned long)samples[i].sample_id,
            (unsigned long)samples[i].t_us,
            samples[i].acc_x, samples[i].acc_y, samples[i].acc_z,
            samples[i].gyr_x, samples[i].gyr_y, samples[i].gyr_z);

        if (pos + slen > (int)(sizeof(chunk) - 8)) {
            if (send_all(sock, chunk, pos) != ESP_OK) return ESP_FAIL;
            pos = 0;
        }
        memcpy(chunk + pos, sbuf, slen);
        pos += slen;
    }

    if (pos + 3 > (int)sizeof(chunk)) {
        if (send_all(sock, chunk, pos) != ESP_OK) return ESP_FAIL;
        pos = 0;
    }
    chunk[pos++] = ']';
    chunk[pos++] = '}';
    chunk[pos++] = '\n';
    if (send_all(sock, chunk, pos) != ESP_OK) return ESP_FAIL;

    return ESP_OK;
}

static esp_err_t transmit_udp_block(int udp_sock, struct sockaddr_in *dest_addr,
                                    uint32_t block_id, sample_data_t *samples, int count,
                                    int odr, int range, const char *mode) {
    const int samples_per_pkt = 15;
    int total_pkts = (count + samples_per_pkt - 1) / samples_per_pkt;

    for (int p = 0; p < total_pkts; p++) {
        int start = p * samples_per_pkt;
        int chunk_cnt = (start + samples_per_pkt > count) ? (count - start) : samples_per_pkt;

        char udp_buf[1400];
        int w = snprintf(udp_buf, sizeof(udp_buf),
            "{\"type\":\"block\",\"block\":%lu,\"part\":%d,\"total_parts\":%d,\"count\":%d,\"odr\":%d,\"range\":%d,\"mode\":\"%s\",\"protocol\":\"UDP\",\"samples\":[",
            (unsigned long)block_id, p + 1, total_pkts, chunk_cnt, odr, range, mode);

        for (int j = 0; j < chunk_cnt; j++) {
            int idx = start + j;
            int n = snprintf(udp_buf + w, sizeof(udp_buf) - w, "%s[%lu,%lu,%.3f,%.3f,%.3f,%.3f,%.3f,%.3f]",
                (j > 0 ? "," : ""),
                (unsigned long)samples[idx].sample_id,
                (unsigned long)samples[idx].t_us,
                samples[idx].acc_x, samples[idx].acc_y, samples[idx].acc_z,
                samples[idx].gyr_x, samples[idx].gyr_y, samples[idx].gyr_z);
            w += n;
        }
        w += snprintf(udp_buf + w, sizeof(udp_buf) - w, "]}\n");

        if (sendto(udp_sock, udp_buf, w, 0, (struct sockaddr*)dest_addr, sizeof(*dest_addr)) < 0) {
            ESP_LOGW(TAG_NET, "Error enviando datagrama UDP: errno %d", errno);
            return ESP_FAIL;
        }
        esp_rom_delay_us(500); // 500 us entre paquetes UDP
    }
    return ESP_OK;
}

