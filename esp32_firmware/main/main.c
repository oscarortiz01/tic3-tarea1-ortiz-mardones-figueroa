static int map_odr_to_reg(int odr) {
    switch (odr) {
        case 12:
        case 13:
        case 125: return BMI270_ODR_12_5;
        case 25:   return BMI270_ODR_25;
        case 50:   return BMI270_ODR_50;
        case 100:  return BMI270_ODR_100;
        case 200:  return BMI270_ODR_200;
        case 400:  return BMI270_ODR_400;
        case 800:  return BMI270_ODR_800;
        case 1600: return BMI270_ODR_1600;
        default:   return BMI270_ODR_100;
    }
}

static int validate_range(int range) {
    if (range == 2 || range == 4 || range == 8 || range == 16) return range;
    return 8;
}

static esp_err_t reconfigure_sensor(int odr, int range) {
    if (!is_bmi270_active) {
        ESP_LOGE(TAG, "Sensor no inicializado");
        return ESP_ERR_INVALID_STATE;
    }
    int odr_reg = map_odr_to_reg(odr);
    int valid_range = validate_range(range);

    ESP_LOGI(TAG, "Reconfigurando BMI270: ODR=%d Hz (reg 0x%02X), Rango=+/- %dg", odr, odr_reg, valid_range);
    acc_conf(odr_reg, 4, valid_range);
    gyr_conf(odr_reg, 2000);

    s_current_acc_range_g = valid_range;
    s_acc_scale_ms2 = ((float)valid_range * 9.80665f) / 32768.0f;
    s_gyr_scale_rads = 34.90659f / 32768.0f;
    s_current_odr_hz = odr;

    return ESP_OK;
}

typedef struct {
    uint32_t sample_id;
    uint32_t t_us;
    float acc_x;
    float acc_y;
    float acc_z;
    float gyr_x;
    float gyr_y;
    float gyr_z;
} sample_data_t;

static esp_err_t bmi270_read_sample(sample_data_t *out) {
    if (out == NULL || !is_bmi270_active) return ESP_ERR_INVALID_STATE;

    uint8_t reg_data = 0x0C;
    uint8_t sensor_data_buffer[12];

    esp_err_t err = device_read(s_dev, &reg_data, sensor_data_buffer, 12, TAG);
    if (err != ESP_OK) return err;

    out->t_us = (uint32_t)esp_timer_get_time();

    int16_t raw_ax = (int16_t)(((uint16_t)sensor_data_buffer[1] << 8) | sensor_data_buffer[0]);
    int16_t raw_ay = (int16_t)(((uint16_t)sensor_data_buffer[3] << 8) | sensor_data_buffer[2]);
    int16_t raw_az = (int16_t)(((uint16_t)sensor_data_buffer[5] << 8) | sensor_data_buffer[4]);

    int16_t raw_gx = (int16_t)(((uint16_t)sensor_data_buffer[7] << 8) | sensor_data_buffer[6]);
    int16_t raw_gy = (int16_t)(((uint16_t)sensor_data_buffer[9] << 8) | sensor_data_buffer[8]);
    int16_t raw_gz = (int16_t)(((uint16_t)sensor_data_buffer[11] << 8) | sensor_data_buffer[10]);

    out->acc_x = (float)raw_ax * s_acc_scale_ms2;
    out->acc_y = (float)raw_ay * s_acc_scale_ms2;
    out->acc_z = (float)raw_az * s_acc_scale_ms2;

    out->gyr_x = (float)raw_gx * s_gyr_scale_rads;
    out->gyr_y = (float)raw_gy * s_gyr_scale_rads;
    out->gyr_z = (float)raw_gz * s_gyr_scale_rads;

    return ESP_OK;
}

