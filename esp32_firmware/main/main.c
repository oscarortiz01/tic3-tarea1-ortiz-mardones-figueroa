/* Extrae datos de aceleración y giroscopio del sensor BMI270, los procesa 
 * e imprime en la salida estándar. Se puede implementar lectura de temperatura. */
esp_err_t bmi270_read(bmi270_reading_t *out) {
    if (out == NULL) {
        return ESP_ERR_INVALID_ARG;
    }

    // No lee nada si el sensor está inactivo
    if (!is_bmi270_active) {
        ESP_LOGW(TAG, "Sensor BMI270 inactivo. Omitiendo lectura.");
        return ESP_ERR_INVALID_STATE;
    }

    uint8_t reg_intstatus = 0x03, tmp;
    int bytes_data8 = 12;
    uint8_t reg_data = 0x0C, sensor_data_buffer[bytes_data8];

    uint16_t acc_x, acc_y, acc_z;
    uint16_t gyr_x, gyr_y, gyr_z;

    float acc_x_ms2, acc_y_ms2, acc_z_ms2;
    float gyr_x_rads, gyr_y_rads, gyr_z_rads;

    ret = device_read(s_dev, &reg_intstatus, &tmp, 1, TAG);
    if (ret != ESP_OK) {
        ESP_LOGE(TAG, "Error leyendo intstatus: %s", esp_err_to_name(ret));
        return ret;
    }

    // Data ready condition
    if ((tmp & 0b10000000) != 0x80) {
        // Todavía no hay muestra nueva; no es un fallo, pero tampoco hay dato.
        return ESP_ERR_NOT_FINISHED;
    }

    {
        ret = device_read(s_dev, &reg_data, (uint8_t*) sensor_data_buffer, bytes_data8, TAG);
        if (ret != ESP_OK) {
            ESP_LOGE(TAG, "Error leyendo datos de acelerómetro y giroscopio: %s", esp_err_to_name(ret));
            return ret;
        }

        // Valores brutos aceleración y giroscopio
        acc_x = ((uint16_t) sensor_data_buffer[1] << 8) | (uint16_t) sensor_data_buffer[0];
        acc_y = ((uint16_t) sensor_data_buffer[3] << 8) | (uint16_t) sensor_data_buffer[2];
        acc_z = ((uint16_t) sensor_data_buffer[5] << 8) | (uint16_t) sensor_data_buffer[4];
        gyr_x = ((uint16_t) sensor_data_buffer[7] << 8) | (uint16_t) sensor_data_buffer[6];
        gyr_y = ((uint16_t) sensor_data_buffer[9] << 8) | (uint16_t) sensor_data_buffer[8];
        gyr_z = ((uint16_t) sensor_data_buffer[11] << 8) | (uint16_t) sensor_data_buffer[10];

        /* CONVERSIÓN CON CONSTANTES FIJAS
         *
         * El chip entrega cada eje como un int16 que cubre +/- el fondo de
         * escala configurado, así que estas tres constantes SOLO valen para los
         * rangos que programa este archivo:
         *
         *     78.4532  = 8 g * 9.80665      -> vale si ACC_RANGE es 8
         *     8.000    = 8 g                -> idem
         *     34.90659 = 2000 deg/s en rad  -> vale si GYR_RANGE es 2000
         *
         * Si se cambia ACC_RANGE o GYR_RANGE arriba, hay que cambiar también
         * estos números o las lecturas salen escaladas por el factor entre los
         * dos rangos. Con GYR_RANGE en 500, por ejemplo, el giroscopio saldría
         * 4x más grande de lo real (2000/500). */

        // Aceleración en m/s2
        acc_x_ms2 = (float)(int16_t)acc_x * s_acc_scale_ms2;
        acc_y_ms2 = (float)(int16_t)acc_y * s_acc_scale_ms2;
        acc_z_ms2 = (float)(int16_t)acc_z * s_acc_scale_ms2;


        // Giroscopio en rad/s
        gyr_x_rads = (float)(int16_t)gyr_x * s_gyr_scale_rads;
        gyr_y_rads = (float)(int16_t)gyr_y * s_gyr_scale_rads;
        gyr_z_rads = (float)(int16_t)gyr_z * s_gyr_scale_rads;

        ESP_LOGD(TAG, "acc_x: %f m/s2  acc_y: %f m/s2  acc_z: %f m/s2", acc_x_ms2, acc_y_ms2, acc_z_ms2);

        out->acc_x_ms2  = acc_x_ms2;
        out->acc_y_ms2  = acc_y_ms2;
        out->acc_z_ms2  = acc_z_ms2;
        out->gyr_x_rads = gyr_x_rads;
        out->gyr_y_rads = gyr_y_rads;
        out->gyr_z_rads = gyr_z_rads;
    }

    return ESP_OK;
}

/* Función para ser llamada desde script main. */
esp_err_t bmi270_init(i2c_master_bus_handle_t bus, int acc_odr, int acc_avg, int acc_range, int gyr_odr, int gyr_range) {
    /* Se agrega al bus que entrega la aplicación. freq_hz = 0 -> usa la
     * velocidad por defecto configurada en i2c_master_init. */
    esp_err_t add_ret = i2c_slave_init(&bus, &s_dev, BMI270_SLAVE_ADDR, 0);
    if (add_ret != ESP_OK) {
        ESP_LOGE(TAG, "No se pudo agregar el slave al bus I2C: %s", esp_err_to_name(add_ret));
        return add_ret;
    }

    is_bmi270_active = false;

    ret = softreset();
    if (ret != ESP_OK) {
        ESP_LOGE(TAG, "Init abortada: softreset falló (%s)", esp_err_to_name(ret));
        return ret;
    }

    ret = chipid();
    if (ret != ESP_OK) {
        ESP_LOGE(TAG, "Init abortada: CHIPID inválido (%s)", esp_err_to_name(ret));        return ret;
    }

    initialization();
    check_initialization();
    toggle_sensors(0, 1, 1, 0);
    acc_conf(acc_odr, acc_avg, acc_range);
    gyr_conf(gyr_odr, gyr_range);
    power_config();
    internal_status();

    return ESP_OK;
}

/* Saca el sensor del bus y anula su handle. */
esp_err_t bmi270_deinit(void) {
    is_bmi270_active = false;
    return i2c_slave_deinit(&s_dev);
}


